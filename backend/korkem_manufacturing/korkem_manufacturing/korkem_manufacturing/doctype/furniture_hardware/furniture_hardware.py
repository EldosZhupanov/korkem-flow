"""Петли, направляющие, ручки — то, чем корпус собирают и открывают.

## Петля — это не бренд

Подойдёт ли петля фасаду, определяют три числа и одно слово: диаметр чашки,
глубина сверления, система присадки и тип наложения. Бренд не определяет ничего:
накладная петля Boyard и накладная петля Blum ставятся одинаково.

Поэтому совместимость здесь — **геометрия, а не список «подходит к»**. Список
пришлось бы вести руками и он разошёлся бы с действительностью на третьей
позиции; геометрия сходится сама.

Подробнее — `docs/product/furniture_reference.md`.
"""

from __future__ import annotations

import frappe
from frappe.model.document import Document

HINGE = "hinge"
RUNNER = "runner"

#: Стандартные диаметры чашки. 35 — для ЛДСП и МДФ, 26 — лёгкие фасады, 40 реже.
CUP_DIAMETERS = (26.0, 35.0, 40.0)


class FurnitureHardware(Document):
	def validate(self):
		"""Отказать в том, чем нельзя работать.

		У петли без чашки и наложения нет присадки — её невозможно поставить.
		У направляющей без длины нет ящика. Остальное дозаполняется позже.
		"""
		if self.hardware_type == HINGE:
			if not self.cup_diameter_mm:
				frappe.throw(
					"У петли должен быть диаметр чашки — без него не сделать присадку."
				)
			if not self.overlay:
				frappe.throw(
					"У петли должен быть тип наложения: накладная, полунакладная "
					"или вкладная. От него зависит, к какому фасаду она подойдёт."
				)

		if self.hardware_type == RUNNER and not self.length_mm:
			frappe.throw("У направляющей должна быть длина — по ней подбирают ящик.")
