"""Плита и кромка — то, из чего режут корпус.

## Почему это не `Item` ERPNext

`Item` отвечает на вопрос «что мы покупаем и продаём»: единица, цена, склад,
проводки. Он не знает ни кода декора, ни толщины, ни того, какая кромка закрывает
какой торец, — а без этого нельзя ни раскроить, ни подобрать пару.

Складским учётом по-прежнему занимается `Item`, и дублировать его здесь нечем:
эта таблица описывает **свойства материала**, а не его запас и цену.

## Почему код декора — отдельное поле

Он устроен осмысленно: `W1000 ST9` — W бельie, 1000 номер, ST9 тиснение. По нему
ищут, по нему заказывают у поставщика, по нему сверяют партию. Название «белый
премиум» не годится: у трёх производителей три разных белых премиума.

Подробнее — `docs/product/furniture_reference.md`.
"""

from __future__ import annotations

import frappe
from frappe.model.document import Document

BOARD = "board"
EDGE = "edge"


class FurnitureMaterial(Document):
	def validate(self):
		"""Отказать в том, чем нельзя работать.

		Проверки ровно две, и обе про раскрой: плита без толщины не режется,
		кромка без привязки к толщине не подбирается. Всё остальное можно
		дозаполнить позже, и мешать этому — значит мешать заводить каталог.
		"""
		if self.kind == BOARD and not self.thickness_mm:
			frappe.throw("У плиты должна быть толщина — без неё не рассчитать раскрой.")

		if self.kind == EDGE and not self.fits_thickness_mm:
			frappe.throw(
				"У кромки должно быть указано, под какую толщину плиты она идёт: "
				"лентой под 18 мм торец 16 мм не закрыть."
			)
