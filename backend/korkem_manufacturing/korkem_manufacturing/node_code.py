"""Показать код первого запуска тому, кто стоит у машины.

    bench --site <сайт> execute korkem_manufacturing.node_code.show

Зачем отдельная команда. Код печатается в поток вывода узла — но только когда
приложение впервые спрашивает сервер, и попадает он в общий журнал вперемешку с
запросами. Владелец первой настоящей установки не смог его там найти:

    «даже я не мог найти код, только с помощью тебя нашёл»

Это дефект поставки, а не невнимательность. Установщику нужна одна команда,
которая отвечает на один вопрос.

Чего эта команда не делает: она **не показывает уже выданный код**. В базе
лежит только его отпечаток — так задумано, и ослаблять это ради удобства
нельзя. Если код уже выдан, а бумажка потеряна, узел перезапускают и получают
новый.
"""

from __future__ import annotations

import frappe

from korkem_manufacturing.services import provisioning


def show() -> None:
	if provisioning.is_claimed():
		company = frappe.db.get_value("Company", {}, "name")
		print(
			f"\nУзел уже принадлежит компании «{company}». "
			"Код первого запуска больше не нужен и не выдаётся.\n"
		)
		return

	if frappe.db.get_default(provisioning.CLAIM_CODE_KEY):
		print(
			"\nКод для этого узла уже выдан, и в открытом виде он нигде не "
			"хранится — в базе только отпечаток.\n"
			"Поищите его в журнале:\n"
			"    docker compose logs bench | grep -A2 'Код для первого запуска'\n"
			"Если не находится — перезапустите узел, и он выдаст новый.\n"
		)
		return

	code = provisioning.claim_code()
	frappe.db.commit()
	print(
		"\n"
		"==================================================================\n"
		"  KORKEM: этот узел пока никому не принадлежит.\n"
		f"  Код для первого запуска: {code}\n"
		"  Введите его в приложении, чтобы создать компанию и владельца.\n"
		"  Код одноразовый и больше нигде не хранится.\n"
		"==================================================================\n"
	)
