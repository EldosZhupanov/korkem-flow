"""Кому что можно сделать с конкретным документом.

## Зачем отдельный модуль

Права в системе живут в трёх слоях, и каждый отвечает на свой вопрос:

* **Роли Frappe** — «имеет ли этот человек доступ к такому *виду* документов».
  Это про доктайп целиком: Sales User видит заказы, все заказы.
* **`scope`** — «чьей компании этот документ». Отдельная ось, которую роли не
  закрывают: на многокомпанейском узле `Sales User` видит заказы всех.
* **Здесь** — «его ли это дело». Задача назначена другому, смена чужая, работа
  не его. Ни роль, ни компания на этот вопрос не отвечают.

Третий слой до сих пор отсутствовал, и его отсутствие было не заметно: код
писал `ignore_permissions=True` и шёл дальше.

## Почему проверка тут, а не в правах Frappe

Правило «своя задача или ты старший» невыразимо ролью: роль не знает, кому
назначена конкретная строка. Выразить его через User Permission тоже нельзя —
назначение меняется каждый день, а разрешения выдаёт администратор.

Поэтому доменная проверка, у которой одна дверь и один текст отказа.

## Что здесь не делается

Не выдаётся и не меняется ни одна роль. Повышать себя нельзя — это R5, и
единственный способ его удержать — чтобы этот модуль умел только отказывать.
"""

from __future__ import annotations

import frappe

from korkem_manufacturing.services import identity, scope

#: Кто может закрыть чужую работу. Не «начальство вообще», а те, чья работа —
#: отвечать за смену: они закрывают за человеком, который ушёл домой или у
#: которого сел телефон.
SUPERVISOR_ROLES = frozenset(
	{
		"System Manager",
		"Korkem Admin",
		"Korkem Shop Manager",
		"Manufacturing Manager",
	}
)


class NotYours(frappe.PermissionError):
	"""Действие законно, но не для этого человека."""


def is_supervisor(user: str | None = None) -> bool:
	return bool(set(frappe.get_roles(user or frappe.session.user)) & SUPERVISOR_ROLES)


def require_can_finish_task(task) -> None:
	"""Закрыть задачу может тот, кому она назначена, или старший смены.

	Порядок проверок — от менее раскрывающей к более: сначала компания (чужую
	задачу не существует), потом назначение. Наоборот было бы подсказкой:
	«эта задача есть, но не твоя» рассказывает о чужой компании больше, чем
	следует.
	"""
	work_order = getattr(task, "reference_docname", None)
	if work_order and getattr(task, "reference_doctype", None) == "Work Order":
		# Компания у задачи не своя, а наследуется от наряда: задача цеха
		# существует только при нём.
		scope.ensure_company("Work Order", work_order)

	if is_supervisor():
		return

	assigned = (getattr(task, "assigned_to", None) or "").strip()
	if not assigned:
		# Ничья задача — не повод для отказа: её берут тем, что закрывают.
		# Отказать здесь значило бы остановить цех ради чистоты правила.
		return

	if assigned != frappe.session.user:
		raise NotYours(
			"Эту задачу закрывает тот, кому она назначена. "
			"Если человек не может — закрыть за него может старший смены."
		)


def role_of(user: str | None = None) -> str:
	"""Реэкспорт, чтобы вызывающим не приходилось знать про два модуля."""
	return identity.role_of(user)
