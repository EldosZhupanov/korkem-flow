"""Сколько строк показано и сколько их на самом деле.

Читающие инструменты возвращают страницу — двадцать записей по умолчанию — и
рядом клали `count`, равный длине этой страницы. Слово честное, смысл читается
наоборот: модель видит «count: 20» и говорит «двадцать заказов», хотя двадцать —
это предел выдачи, а заказов двадцать четыре.

Найдено живым ходом ассистента: на вопрос «сколько заказов в работе» он ответил
«из 20 активных», когда их было 24. Владелец принимает решения по этим числам, и
число, означающее размер страницы, для него ничем не отличается от итога.

Отсюда три поля вместо одного:

* `count` — сколько строк в этом ответе. Оставлено, потому что на него уже
  ссылаются тесты и чужой код, и потому что оно не врёт про себя;
* `total` — сколько записей всего под этими же условиями;
* `truncated` — показано не всё.

Лишний запрос на подсчёт стоит одну строку SQL. Неверное число в ответе
владельцу стоит дороже.
"""

from __future__ import annotations

import frappe


def page(rows: list, doctype: str, filters: dict | list | None = None) -> dict:
	"""Три поля, которыми страница описывает саму себя.

	Считается по тем же условиям, что и выборка. Если посчитать не вышло —
	говорим об этом прямо, а не подставляем длину страницы: «не знаю, сколько
	всего» — честный ответ, «двадцать» на месте неизвестного — нет.
	"""
	shown = len(rows)
	try:
		total = frappe.db.count(doctype, filters or {})
	except Exception:
		frappe.log_error(
			title=f"Could not count {doctype} for a tool result",
			message=frappe.get_traceback(with_context=True),
		)
		return {"count": shown, "total": None, "truncated": None}

	return {"count": shown, "total": total, "truncated": shown < total}
