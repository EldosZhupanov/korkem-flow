"""Один факт, который KORKEM помнит между разговорами.

## Чего здесь не будет никогда

**Память не является источником правды ни для одного изменяемого факта.**
Заказы, остатки, цены, оплаты, долги, сроки и состояние производства живут в
ERPNext, и только там. Память хранит устойчивое: должность человека, кто за что
отвечает, как в этом цехе называют вещи, какие правила подтвердил владелец.

Разница не философская. Остаток «ЛДСП 40 листов», записанный в память, к вечеру
станет ложью — и ассистент будет уверенно называть число, которого нет.
Ошибиться при этом дешевле всего тому, кто спрашивал: он поверит.

Правило проверяется в `validate`, а не только написано здесь. Написанное
правило нарушают через полгода, не заметив.

## Почему у факта есть срок и замена

«Нурлан основной оператор ЧПУ» верно сегодня и неверно, когда Нурлан уволился.
Факт без возможности устареть — это факт, который однажды начнёт врать молча.
Поэтому у каждого есть источник, время, уверенность и `superseded_by`: новый
факт не затирает старый, а становится ему на смену, и историю видно.

Подтверждённый человеком факт живёт дольше выведенного: человек знает свой цех
лучше, чем модель, которая его слушала.
"""

from __future__ import annotations

import frappe
from frappe.model.document import Document

#: Слова, за которыми стоит изменяемое состояние бизнеса.
#:
#: Не запрет на тему разговора, а запрет на **запоминание числа**, которое
#: завтра станет другим. «Мы считаем ЛДСП в квадратных метрах» — терминология и
#: остаётся; «ЛДСП сейчас 40 листов» — остаток, и ему место в ERPNext.
VOLATILE_HINTS = (
	"остаток",
	"остатки",
	"на складе",
	"цена",
	"стоимость",
	"сумма заказа",
	"статус заказа",
	"оплачен",
	"долг",
	"задолженность",
	"баланс",
)

#: Секреты. Не «не рекомендуется», а не должно оказаться в базе памяти вовсе.
SECRET_HINTS = ("пароль", "password", "api key", "api-ключ", "токен", "token", "secret", "cvv", "пин-код")


class MemoryFact(Document):
	def validate(self):
		self.subject = (self.subject or "").strip()
		self.predicate = (self.predicate or "").strip()
		self.value = (self.value or "").strip()

		if self.scope == "user" and not self.owner_key:
			frappe.throw("Факт о человеке без человека — это факт ни о ком.")
		if self.scope == "company" and self.owner_key:
			frappe.throw(
				"Факт компании принадлежит компании. Если он про одного человека, "
				"это факт области «user»."
			)

		self._refuse_secrets()
		self._refuse_volatile_business_state()

		for field in ("confidence", "importance"):
			value = self.get(field)
			if value is None:
				continue
			if not 0 <= value <= 1:
				frappe.throw(f"«{field}» — это доля от нуля до единицы.")

	def _refuse_secrets(self):
		"""Секрет, попавший в память, оттуда уже не исчезнет.

		Память читается при сборке контекста и уходит в модель. Ключ, случайно
		сохранённый как «предпочтение», уедет к провайдеру в первом же запросе.
		"""
		haystack = f"{self.subject} {self.predicate} {self.value}".lower()
		for hint in SECRET_HINTS:
			if hint in haystack:
				frappe.throw(
					"Похоже на секрет. Пароли, ключи и токены в памяти не хранятся: "
					"память уходит в модель, а секреты — нет."
				)

	def _refuse_volatile_business_state(self):
		"""Изменяемое состояние живёт в ERPNext, а не здесь.

		Отказ, а не предупреждение: предупреждение читают один раз и обходят.
		"""
		if self.category in ("terminology", "rule"):
			# Терминология и правила законно упоминают склад и цены: «цены
			# храним без НДС», «остаток считаем по факту, а не по документам».
			# Здесь запоминается способ считать, а не само число.
			return

		haystack = f"{self.subject} {self.predicate} {self.value}".lower()
		for hint in VOLATILE_HINTS:
			if hint in haystack:
				frappe.throw(
					f"«{hint}» — это изменяемое состояние, и оно живёт в ERPNext. "
					"Память хранит устойчивое: должности, терминологию, правила. "
					"Запомненный остаток к вечеру станет ложью, которую ассистент "
					"назовёт уверенно."
				)
