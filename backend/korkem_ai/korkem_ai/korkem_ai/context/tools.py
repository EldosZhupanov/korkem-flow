#: Область, которая идёт всегда.
#:
#: Один инструмент в двадцать три токена: без него модель не может ответить
#: даже на «кто я», а цена этого — ничто.
ALWAYS = ("profile",)


def query_laya_router(question: str) -> dict | None:
	"""Запрос к локальному System 1 микросервису Laya."""
	url = os.environ.get("LAYA_ROUTER_URL", "http://laya-router:8001")
	candidate_urls = [url]
	if "laya-router" in url:
		candidate_urls.append("http://127.0.0.1:8001")

	for target in candidate_urls:
		try:
			req = urllib.request.Request(
				f"{target}/v1/route",
				data=json.dumps({"text": question}).encode("utf-8"),
				headers={"Content-Type": "application/json"},
				method="POST",
			)
			with urllib.request.urlopen(req, timeout=1.0) as resp:
				if resp.status == 200:
					return json.loads(resp.read().decode("utf-8"))
		except Exception:
			continue
	return None


def select(question: str) -> tuple[list[str], bool]:
	"""Области для этого вопроса и признак «слова не узнались».

	1. Быстрый проход: проверка ключевых корней (0.01 мс).
	2. Семантический проход: локальный микросервис Laya System 1 (30-50 мс).
	3. Деградация: показ всех инструментов, если оба прохода не дали результата.
	"""
	text = (question or "").lower()
	hit = {
		domain
		for domain, words in DOMAIN_WORDS.items()
		if any(word in text for word in words)
	}
	if hit:
		return sorted(hit | set(ALWAYS)), False

	# Если ключевые слова не дали совпадения — опрашиваем Laya System 1
	laya_res = query_laya_router(question)
	if laya_res and isinstance(laya_res, dict):
		domain = laya_res.get("domain")
		if domain and domain in DOMAIN_WORDS and domain != "profile":
			return sorted({domain} | set(ALWAYS)), False

	return sorted(DOMAIN_WORDS), True


def offered(question: str, *, all_specs=None) -> tuple[list, dict]:
	"""Инструменты для этого вопроса и что это дало.

	Возвращает то же, что `registry.offered_to`, но отфильтрованное — и разбивку
	по токенам, потому что человек должен видеть, из чего сложился его запрос.
	"""
	specs = all_specs if all_specs is not None else registry.offered_to()
	domains, unmatched = select(question)

	kept = [spec for spec in specs if _domain_of(spec) in domains]
	# Пустой отбор означает, что словарь разошёлся с каталогом: вопрос узнан, а
	# инструментов такой области нет. Показываем всё — молчащий ассистент хуже
	# дорогого.
	if not kept:
		kept, unmatched = list(specs), True

	return kept, {
		"domains": domains,
		"unmatched": unmatched,
		"offered": len(kept),
		"total": len(specs),
		"tokens": _tokens(kept),
		"tokens_if_all": _tokens(specs),
	}


def _domain_of(spec) -> str:
	name = getattr(spec, "name", "")
	return name.split(".")[0] if "." in name else "прочее"


def _tokens(specs) -> int:
	"""Оценка, а не измерение.

	Токенизатор у каждого провайдера свой, и точное число известно только после
	ответа. Четыре символа на токен — грубое правило, одинаковое для всех
	строк отчёта, поэтому сравнивать разделы между собой оно позволяет.
	"""
	size = sum(
		len(getattr(spec, "description", "") or "")
		+ len(json.dumps(getattr(spec, "input_schema", {}), ensure_ascii=False))
		+ len(getattr(spec, "name", ""))
		for spec in specs
	)
	return size // 4
