"""Какие инструменты показать модели на этот вопрос.

## Зачем это существует

Измерено на живом наборе 4 сентября 2026:

    инструкция              682 токена
    схемы 65 инструментов  8877 токенов   — 93% запроса
    итого на пустом ходу    9559 токенов

Девяносто три процента уходит на перечисление того, что ассистент *умеет*, ещё
до того как человек что-то спросил. Один ход стоит трёх обращений к модели —
около 28 700 токенов на вопрос, почти целиком на каталог.

Вопрос «есть ли материал на кухню?» не нуждается в схемах отгрузки, договоров и
рабочих мест. Он нуждается в складе.

## Почему правилами, а не моделью

Отдельный вызов модели ради выбора инструментов стоил бы того же, что мы
пытаемся сэкономить, и добавил бы задержку к каждому вопросу. Область
определяется словами вопроса — и это работает, потому что цех говорит о своём
деле своими словами: «остаток», «раскрой», «счёт», «замер».

## Что происходит, когда слова не узнались

Показываем **всё**. Не половину и не «самое частое»: ассистент, у которого нет
нужного инструмента, отвечает «не умею» на то, что умеет, и человек перестаёт
спрашивать. Незнакомый вопрос стоит столько же, сколько стоил раньше — это не
ухудшение, а отсутствие улучшения, и оно видно в учёте.
"""

from __future__ import annotations

import json

from korkem_ai.korkem_ai.tools import registry

#: Слова, по которым узнаётся область. Русские и казахские: мастер у станка
#: пишет на том языке, на котором думает, и половина цеха думает по-казахски.
#:
#: Корни, а не полные слова: «остаток», «остатки», «остатке» — одно и то же для
#: склада, и перечислять падежи значит однажды забыть один.
DOMAIN_WORDS: dict[str, tuple[str, ...]] = {
	"inventory": (
		"склад", "остат", "материал", "лдсп", "кромк", "фурнитур", "плит",
		"хватает", "резерв", "қойма", "материал", "қалды",
	),
	"procurement": (
		"закуп", "поставщик", "заказать у", "приход", "накладн", "счёт от",
		"жеткізуші", "сатып ал",
	),
	"manufacturing": (
		"производств", "цех", "станок", "операц", "распил", "раскро", "кромлен",
		"чпу", "фрезер", "сборк", "покрас", "смен", "өндіріс", "станок",
	),
	"crm": (
		"клиент", "лид", "звонил", "написал", "контакт", "заявк", "обращен",
		"сделк", "клиент", "тапсырыс беруші",
	),
	"sales": (
		"кп", "предложен", "цена", "счёт", "оплат", "стоимость", "договор",
		"продаж", "баға", "төлем", "шот",
	),
	"dispatch": (
		"отгруз", "доставк", "монтаж", "установк", "машин", "жеткіз", "монтаж",
	),
	"chain": (
		"замер", "дизайн", "чертёж", "спецификац", "базис", "гаранти", "брак",
		"переделк", "этап", "өлшеу", "жоба",
	),
	"tasks": ("задач", "поручен", "срок", "просроч", "тапсырма", "мерзім"),
	"profile": ("кто я", "мои права", "моя роль", "менің"),
}

#: Область, которая идёт всегда.
#:
#: Один инструмент в двадцать три токена: без него модель не может ответить
#: даже на «кто я», а цена этого — ничто.
ALWAYS = ("profile",)


def select(question: str) -> tuple[list[str], bool]:
	"""Области для этого вопроса и признак «слова не узнались».

	Второе значение важнее первого для учёта: по нему видно, как часто мы
	платим полную цену, и стоит ли расширять словарь.
	"""
	text = (question or "").lower()
	hit = {
		domain
		for domain, words in DOMAIN_WORDS.items()
		if any(word in text for word in words)
	}
	if not hit:
		return sorted(DOMAIN_WORDS), True
	return sorted(hit | set(ALWAYS)), False


def offered(question: str, *, all_specs=None) -> tuple[list, dict]:
	"""Инструменты для этого вопроса и что это дало.

	Возвращает то же, что `registry.offered_to`, но отфильтрованное — и разбивку
	по токенам, потому что человек должен видеть, из чего сложился его запрос.
	"""
	specs = all_specs if all_specs is not None else registry.offered_to()
	domains, unmatched = select(question)

	kept = [spec for spec in specs if _domain_of(spec) in domains]
	# Пустой отбор означает, что словарь разошёлся с каталогом: вопрос узнан, а
	# инструментов такой области нет. Показываем всё — молчащий ассистент хуже
	# дорогого.
	if not kept:
		kept, unmatched = list(specs), True

	return kept, {
		"domains": domains,
		"unmatched": unmatched,
		"offered": len(kept),
		"total": len(specs),
		"tokens": _tokens(kept),
		"tokens_if_all": _tokens(specs),
	}


def _domain_of(spec) -> str:
	name = getattr(spec, "name", "")
	return name.split(".")[0] if "." in name else "прочее"


def _tokens(specs) -> int:
	"""Оценка, а не измерение.

	Токенизатор у каждого провайдера свой, и точное число известно только после
	ответа. Четыре символа на токен — грубое правило, одинаковое для всех
	строк отчёта, поэтому сравнивать разделы между собой оно позволяет.
	"""
	size = sum(
		len(getattr(spec, "description", "") or "")
		+ len(json.dumps(getattr(spec, "input_schema", {}), ensure_ascii=False))
		+ len(getattr(spec, "name", ""))
		for spec in specs
	)
	return size // 4
